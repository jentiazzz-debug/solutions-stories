        f"{ratios}\n\n"
        "<b>2. Пришли фото и выбери число частей.</b> Перед оплатой покажу "
        "превью — сразу видно, не разрезано ли лицо по шву.\n\n"
        "<b>3. Публикуй файлы подряд, сверху вниз.</b> Бот отдаёт их уже в "
        "порядке публикации: первый файл — правый нижний угол, последний — "
        "левый верхний.\n\n"
